<?php

// Declaring numbers
$a = 10;
$b = 5;

// Arithmetic operations
echo $a + $b . '<br>';      // 15
echo $a - $b . '<br>';      // 5
echo $a * $b . '<br>';      // 50
echo $a / $b . '<br>';      // 2
echo $a % $b . '<br><br>';  // 0

// Assignment with math operators
$a += $b; echo $a.'<br>';   // $a = 15
$a -= $b; echo $a.'<br>';   // $a = 10
$a *= $b; echo $a.'<br>';   // $a = 50
$a /= $b; echo $a.'<br>';   // $a = 10
$a %= $b; echo $a.'<br>';   // $a = 0